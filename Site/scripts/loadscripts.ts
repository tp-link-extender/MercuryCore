// Generates the types of the 2013 loadscripts from the manifest the 2013 compile step writes.
// Run with `bun scripts/loadscripts.ts`. The manifest is at Site/src/lib/server/loadscripts.manifest.json.

import path from "node:path"

export const manifestPath = path.join(
	import.meta.dir,
	"../src/lib/server/loadscripts.manifest.json"
)
export const outputPath = path.join(
	import.meta.dir,
	"../src/lib/server/loadscripts.gen.ts"
)

export interface Manifest {
	[_: string]: string[]
}

const isStringList = (value: unknown): value is string[] =>
	Array.isArray(value) && value.every(item => typeof item === "string")

/** Reads a manifest, refusing anything that isn't a name with a list of placeholder names. */
export function parseManifest(text: string): Manifest {
	const data: unknown = JSON.parse(text)
	if (typeof data !== "object" || data === null || Array.isArray(data))
		throw new TypeError("Loadscript manifest must be an object")

	const manifest: Manifest = {}
	for (const [name, placeholders] of Object.entries(data)) {
		if (!isStringList(placeholders))
			throw new TypeError(`Loadscript manifest entry ${name} must be a list of placeholder names`)
		manifest[name] = placeholders
	}
	return manifest
}

/** Turns a loadscript's name into the start of its type's name, such as host2016 into Host2016. */
const pascal = (name: string): string =>
	name.charAt(0).toUpperCase() + name.slice(1)

/** Writes the TypeScript for a manifest. Names are sorted, so the output doesn't depend on the order the manifest lists them in. */
export function generate(manifest: Manifest): string {
	const names = Object.keys(manifest).toSorted()
	for (const name of names)
		if (!/^[a-z][A-Za-z0-9]*$/.test(name))
			throw new TypeError(`Loadscript name ${name} isn't a plain identifier, so it can't be a type`)
	let out = `// Code generated by scripts/loadscripts.ts from loadscripts.manifest.json. DO NOT EDIT.

import type { LoadscriptValue } from "./loadscript.ts"

`

	for (const name of names) {
		const placeholders = manifest[name].toSorted()
		out += `export type ${pascal(name)}Values = `
		if (placeholders.length === 0) {
			out += "{ [_: string]: never }\n\n"
			continue
		}
		out += "{\n"
		for (const p of placeholders) out += `\t${p}: LoadscriptValue\n`
		out += "}\n\n"
	}

	out += "export type LoadscriptValuesByName = {\n"
	for (const name of names) out += `\t${name}: ${pascal(name)}Values\n`
	out += "}\n\n"
	out += "export type LoadscriptName = keyof LoadscriptValuesByName\n"
	return out
}

if (import.meta.main) {
	const manifest = parseManifest(await Bun.file(manifestPath).text())
	await Bun.write(outputPath, generate(manifest))
	console.log(`Wrote ${outputPath}`)
}
